// Flattened [{ role, module, level }] shape — convenient for prisma upserts.
function toRows() {
  const rows = []
  for (const role of Object.keys(DEFAULT_PERMISSIONS)) {
    for (const module of MODULES) {
      rows.push({ role, module, level: DEFAULT_PERMISSIONS[role][module] ?? 'NONE' })
    }
  }
  return rows
}

